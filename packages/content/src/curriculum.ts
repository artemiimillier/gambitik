/** Stage lookup clamped to the valid range 1..10. */
export function getCurriculumStage(stage: number): CurriculumStage {
  const last = CURRICULUM.length;
  const n = Number.isFinite(stage) ? Math.min(last, Math.max(1, Math.trunc(stage))) : 1;
  // CURRICULUM is ordered by stage and has no gaps (covered by tests).
  return CURRICULUM[n - 1] as CurriculumStage;
}

/** The stage after `stage`, or null on the last one. */
export function getNextCurriculumStage(stage: number): CurriculumStage | null {
  const current = getCurriculumStage(stage);
  return current.stage >= CURRICULUM.length ? null : getCurriculumStage(current.stage + 1);
}
