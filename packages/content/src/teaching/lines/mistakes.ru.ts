/**
 * Wordings of «Учитель» — family «mistakes» (docs/TEACHING.md §5; pool specs: ../spec.ts).
 * Rules: no Latin, NO squares (the board shows them), Гамбитик speaks of himself as a boy, the child through {g:…},
 * no «молодец», no clock words; «вот эти клетки / этот фланг / сюда» only in pools with a board cue.
 *
 * What these lines are for (§2.8): right after the child's move, while the bot thinks — what happened, by a concept
 * (`v3.mistake.*`, without squares and without blame), the rule to remember (`v3.rule.*`, first time in a game) or the
 * same rule as a question (`v3.rule.ask.*`, stages 3–5, second time); the take-back offer (`v3.takeback.*`):
 * stages 1–2 «Стоп-стоп! {что случилось}. Вернём ход?», stages 3–5 «Стоп! Что теперь может съесть соперник?».
 * The opponent has not answered yet: the mistake lines speak of what he CAN do now («соперник может…»).
 * A mistake line explains the consequence of OUR move; the alarms («Осторожно!», «Берегись!») belong to `v3.danger.*`.
 * Stages 3–5 hear a mistake line again after the take-back reply (reaction.ts), so the older and shared wordings avoid
 * «теперь» and «ход сделан» where they can (after «Верну» the move is no longer on the board).
 * Openers (the ear hears the first words; a game also hears `v3.danger.*`, which own «Соперник может съесть…»):
 * no mistake wording opens with «Соперник может съесть»; per pool at most 2 wordings open with «Соперник может»,
 * at most 2 with «{Конь} соперника», and per band at most 2 with «{Твой} {конь}» / «{Твоего} {коня}».
 * The take-back replies: `yes` / `no` stand alone at stages 1–2 and are followed by a mistake line at 3–5; `again`
 * opens the second offer — at stages 1–2 a mistake line and «Вернём ход?» follow, at 3–5 an `askThink` question, so
 * `again` is a statement, never a question.
 * Never: «ошибка», «зевок», «ты не…», «забыл», «зря», «опять», «снова», «неверно», «молодец», «так держать».
 *
 * Chess truth the words keep to (core coach/lesson/mistake.ts, analysis/motifs.ts):
 *  - fork: the forker is never the king, the targets are pieces or the king (never pawns);
 *  - pin / trapped: the victim is a knight, bishop, rook or queen; a pin is to the king OR to a dearer piece, so the
 *    words say «уходить нельзя / трудно / опасно», never «не сможет уйти» as a law;
 *  - backRank: the king's front squares are blocked by his own men — not necessarily pawns;
 *  - hanging.cheaper: the victim is defended, a cheaper piece attacks it; outnumbered: more attackers than defenders;
 *  - ignoredDanger: the warned piece stayed where it was — it may have got a defender that was not enough;
 *  - missedTreasure: the gift may be a mate or a fork (no piece) — piece-free wordings exist; never «бесплатно»;
 *  - slower: the engine does not prove «без потерь», so no wording claims it.
 */
