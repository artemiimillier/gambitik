/**
 * Wordings of «Учитель» — family «endings» (docs/TEACHING.md §2.9, §5; pool specs: ../spec.ts).
 * Rules: no Latin, NO squares (the board shows them), Гамбитик speaks of himself as a boy, the child through {g:…},
 * no «молодец / умница / так держать», no clock words; «вот эти клетки / этот фланг / сюда» only in pools with a board cue.
 *
 * `v3.end.*` — ONE sentence that opens the end of the game: the feelings (joy / support) live HERE, never «молодец»; it
 * is generic about HOW the game ended (a win may be a mate, a resignation or the clock; a draw may be a stalemate).
 *
 * `v3.takeaway.*` — the LESSON of the game to carry into the next one, NOT praise (the opener already did the feelings):
 * a concrete rule or habit + WHY, 1–2 short sentences (≤ 14 words each). It is also shown alone on the result card, so it
 * reads without the opener and stays true after a win, a loss or a draw.
 *  - `mistake.*` — «В следующий раз / На будущее: <правило> — <зачем>». A fact about the game only as «был / мог»,
 *    never «ты проиграл из-за…», no reproach («ты не», «забыл», «зря», «опять», «снова»). Same idea as the in-game
 *    rule (`v3.rule.*`) of that concept, fresh words.
 *  - `theme.*` — the fact that the theme worked (never «поэтому выиграли»; no claim about the king's safety NOW — a theme
 *    takeaway may follow a lost game) + what to keep doing and why. The engine proves only «two goals of the card done»,
 *    so the fact stays soft («план с центром удался»), the habit carries the lesson.
 *  - `found.*` — what the child found (the motif is unknown: «сильный ход / удар / подарок», a mate is a mate) + HOW such
 *    moves are found, to keep doing it. The find is the child's own move, but an arrow may have pointed elsewhere and at
 *    stages 1–2 the target of a treasure is lit — so no «без стрелки / без подсказки», only «сам», «своими глазами».
 *    No «зоркие глаза / какая внимательность / это здорово» — that is praise, not a lesson.
 *  - `quiz.*` — the kind of question the child answered well + the habit behind the question and why it matters.
 *  - `stage.*` — the stage's advice as a rule + why.
 * The child's gender goes through {g:…} and never as «ты …л» (the lint reads the expanded text, so «ты {g:нашёл|нашла}»
 * is flagged too — write «{g:Сам|Сама} {g:нашёл|нашла}» or an impersonal form).
 */
