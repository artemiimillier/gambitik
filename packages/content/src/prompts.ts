// ───────────────────────── review prompt builder ─────────────────────────

/** Classifications worth sending to the text model in full (the rest are summarised by counts). */
const NOTABLE_CLASSES: ReadonlySet<MoveJudgement['classification']> = new Set([
  'inaccuracy',
  'mistake',
  'blunder',
  'missedWin',
]);

/**
 * Event types the review may mention. Bulk 'move' and 'coachSaid' events are dropped to keep the prompt small.
 * PRIVACY: 'childSaid' is deliberately NOT in this list — what a 7–10 year old tells a
 * talking mascot never leaves the computer inside a review prompt. Do not add it.
 */
const REVIEW_EVENT_TYPES: ReadonlySet<GameEvent['type']> = new Set([
  'takebackOffered',
  'takebackAccepted',
  'takebackDeclined',
  'hintRequested',
  'hintGiven',
]);

const MAX_NOTABLE_JUDGEMENTS = 12;
const MAX_GOOD_JUDGEMENTS = 4;
const MAX_REVIEW_EVENTS = 30;
/** Good moves in the first plies are usually plain opening moves — not worth praising in a review. */
const BOOK_PLIES = 10;

export interface ReviewPromptInput {
  record: GameRecord;
  /** Only the pseudonym, the grammatical address and the stage are ever sent to the model. */
  student?: Pick<StudentProfile, 'nickname' | 'address' | 'stage'>;
  /** Russian display name of the bot, e.g. 'Саша'. */
  personaName?: string;
}

function slimJudgement(j: MoveJudgement): Record<string, unknown> {
  return {
    ply: j.ply,
    san: j.san,
    classification: j.classification,
    winPctLoss: Math.round(j.winPctLoss),
    bestSan: j.bestSan,
    bestPvSan: j.bestPvSan.slice(0, 3),
    refutationPvSan: j.refutationPvSan.slice(0, 3),
    allowedMotif: j.allowedMotif,
    missedMotif: j.missedMotif,
    materialLossPawns: j.materialLossPawns,
  };
}

/**
 * REVIEW_PROMPT_RU + a compact JSON payload built from the GameRecord.
 * The payload keeps everything the prompt refers to (result, summary with key moments, the worst
 * and the best judged moves, take-back / hint events) and drops bulky fields
 * and everything the child said
 * (FENs, engine evals, the full move event stream) so it stays small enough for a cheap model.
 */
export function buildReviewPrompt(input: ReviewPromptInput): string {
  const { record, student, personaName } = input;

  const notable = record.judgements
    .filter((j) => NOTABLE_CLASSES.has(j.classification))
    .sort((a, b) => b.winPctLoss - a.winPctLoss)
    .slice(0, MAX_NOTABLE_JUDGEMENTS);
  const good = record.judgements
    .filter((j) => j.classification === 'best' || j.classification === 'excellent')
    .filter((j) => j.ply > BOOK_PLIES)
    .slice(-MAX_GOOD_JUDGEMENTS);
  const judgements = [...notable, ...good].sort((a, b) => a.ply - b.ply).map(slimJudgement);

  const events = record.events
    .filter((e) => REVIEW_EVENT_TYPES.has(e.type))
    .slice(0, MAX_REVIEW_EVENTS)
    .map((e) => ({ type: e.type, ply: e.ply, data: e.data }));

  const payload = {
    game: {
      id: record.id,
      startedAt: record.startedAt,
      personaId: record.personaId,
      personaName,
      timeControlId: record.timeControlId,
      childColor: record.childColor,
      result: record.result,
      termination: record.termination,
      examMode: record.examMode,
    },
    student: student ? { nickname: student.nickname, address: student.address, stage: student.stage } : undefined,
    summary: record.summary,
    judgements,
    events,
    pgn: record.pgn,
  };

  return `${REVIEW_PROMPT_RU}\n${JSON.stringify(payload, null, 1)}\n`;
}
