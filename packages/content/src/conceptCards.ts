const CARD_BY_ID: ReadonlyMap<string, ConceptCard> = new Map(CONCEPT_CARDS.map((card) => [card.id, card]));

/** The main card of a motif is the first card in CONCEPT_CARDS that declares it. */
export function getConceptCardByMotif(motif: MotifId): ConceptCard | undefined {
  return CONCEPT_CARDS.find((card) => card.motif === motif);
}

/** First card that lists the given Lichess puzzle theme key. */
export function getConceptCardByTheme(theme: string): ConceptCard | undefined {
  return CONCEPT_CARDS.find((card) => card.lichessThemes.includes(theme));
}

/**
 * Card lookup for `GET /api/kb/:id` and the coach.
 * Accepts a card id ('fork', 'endgame-opposition'); as a convenience it also resolves a MotifId
 * ('hangingPiece') or a Lichess theme key ('capturingDefender') to the matching card.
 */
export function getConceptCard(id: string): ConceptCard | undefined {
  return CARD_BY_ID.get(id) ?? CONCEPT_CARDS.find((card) => card.motif === id) ?? getConceptCardByTheme(id);
}

/** Cards introduced at exactly this curriculum stage. */
export function getConceptCardsForStage(stage: number): ConceptCard[] {
  return CONCEPT_CARDS.filter((card) => card.stage === stage);
}
